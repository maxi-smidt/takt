#!/usr/bin/env node
// Concatenates the real component stylesheets (webui/src/shared/ui/tokens.css
// + ui.css) into design-system/styles.css, so the Claude Design project
// consuming that file can never drift from what the app actually ships.
// Run after any change to those two files, before re-uploading the bundle.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const tokensPath = join(repoRoot, "webui/src/shared/ui/tokens.css");
const uiPath = join(repoRoot, "webui/src/shared/ui/ui.css");
const outPath = join(repoRoot, "design-system/styles.css");

const tokens = readFileSync(tokensPath, "utf8");
// ui.css starts with `@import "./tokens.css";` — drop it, tokens.css is
// inlined directly above instead.
const ui = readFileSync(uiPath, "utf8").replace(/^@import "\.\/tokens\.css";\n+/, "");

const banner = `/*
 * GENERATED by scripts/build_design_bundle.mjs from
 * webui/src/shared/ui/tokens.css + ui.css. Do not hand-edit — change those
 * two files and re-run the script instead.
 */

`;

writeFileSync(outPath, banner + tokens + "\n" + ui);
console.log(`Wrote ${outPath}`);
